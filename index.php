  <script>
    // Ждём загрузки страницы
    document.addEventListener('scroll', () => {
      const shapka = document.querySelector('.shapka');
      const nav = document.querySelector('.nav');

      if (window.scrollY > 50) {
        shapka.classList.add('shrink');
        nav.classList.add('shrink');
      } else {
        shapka.classList.remove('shrink');
        nav.classList.remove('shrink');
      }
    });





    const img = document.getElementById('scrollImage');
    const startOffset = 108;

    window.addEventListener('scroll', () => {
      const scrollY = window.scrollY;
      const maxScroll = document.documentElement.scrollHeight - window.innerHeight;

      if (scrollY < startOffset) {
        img.style.opacity = '0';
        img.style.transform = 'translateY(0)';
        return;
      }

      // Прогресс от 0 до 1
      const progress = (scrollY - startOffset) / (maxScroll - startOffset);
      const clamped = Math.min(Math.max(progress, 0), 1);

      // Картинка поднимается так, чтобы в конце она почти полностью была видна
      // 0% — только появляется снизу
      // 100% — верх картинки почти у верхнего края экрана
      const move = clamped * (window.innerHeight - 50); // 80px — отступ сверху

      img.style.opacity = '1';
      img.style.transform = `translateY(-${move}px)`;
    });










    const lightbox = document.getElementById('lightbox');
    const lightboxImg = document.getElementById('lightboxImg');
    const lightboxVideo = document.getElementById('lightboxVideo');

    // Все элементы галереи (фото + видео)
    const galleryItems = document.querySelectorAll('.gallery_img');

    galleryItems.forEach(item => {
      item.addEventListener('click', () => {
        // Сбрасываем предыдущее
        lightboxImg.classList.remove('active');
        lightboxVideo.classList.remove('active');
        lightboxVideo.pause();
        lightboxVideo.removeAttribute('src');

        if (item.tagName === 'VIDEO') {
          // Это видео
          const source = item.querySelector('source');
          lightboxVideo.src = source ? source.src : item.src;
          lightboxVideo.classList.add('active');
          lightboxVideo.play(); // запускаем только при открытии
        } else {
          // Это фото
          lightboxImg.src = item.src;
          lightboxImg.alt = item.alt || '';
          lightboxImg.classList.add('active');
        }

        lightbox.classList.add('active');
        document.body.style.overflow = 'hidden';
      });
    });

    // Закрытие по клику
    lightbox.addEventListener('click', () => {
      lightbox.classList.remove('active');
      lightboxVideo.pause();
      lightboxVideo.currentTime = 0;
      document.body.style.overflow = '';
    });






    const galleryButtons = document.querySelectorAll('.nav_button[data-gallery]');
    const galleryMain = document.getElementById('gallery_main');
    const galleryVisitors = document.getElementById('gallery_visitors');

    galleryButtons.forEach(button => {
      button.addEventListener('click', () => {
        const target = button.dataset.gallery;

        // Активная кнопка
        galleryButtons.forEach(btn => btn.classList.remove('videleno'));
        button.classList.add('videleno');

        // Переключаем галереи
        if (target === 'main') {
          galleryMain.classList.remove('is-hidden');
          galleryVisitors.classList.add('is-hidden');
        } else {
          galleryMain.classList.add('is-hidden');
          galleryVisitors.classList.remove('is-hidden');
        }
      });
    });
  </script>
